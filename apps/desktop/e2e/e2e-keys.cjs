// Saving a setup with and without stream keys, and loading both, through the screens.
//   xvfb-run -a node e2e/e2e-keys.cjs   (after `pnpm --filter @obs-config-loader/desktop build`)
const { _electron: electron } = require('playwright')
const fs = require('fs'), path = require('path'), os = require('os')
const JSZip = require(require.resolve('jszip', { paths: [path.resolve(__dirname, '../../../packages/core')] }))
const APP = path.resolve(__dirname, '..')
const OUT = path.join(os.tmpdir(), 'obscl-e2e-shots')
fs.mkdirSync(OUT, { recursive: true })
const check = (name, cond) => { console.log(cond ? '  ok  ' : '  FAIL', name); if (!cond) process.exitCode = 1 }

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'e2e-keys-'))
const home = path.join(root, 'home')
const cfg = path.join(home, '.var/app/com.obsproject.Studio/config/obs-studio')
fs.mkdirSync(path.join(cfg, 'basic/scenes'), { recursive: true })
fs.mkdirSync(path.join(cfg, 'basic/profiles/Main'), { recursive: true })
fs.mkdirSync(path.join(home, '.local/share/flatpak/app/com.obsproject.Studio'), { recursive: true })
fs.writeFileSync(path.join(cfg, 'basic/scenes/Main.json'), JSON.stringify({ name: 'Main', sources: [{ id: 'scene', name: 'Scene', settings: { items: [] } }] }))
fs.writeFileSync(path.join(cfg, 'basic/profiles/Main/basic.ini'), '[General]\nName=Main\n')
fs.writeFileSync(path.join(cfg, 'basic/profiles/Main/service.json'), JSON.stringify({ type: 'rtmp_common', settings: { service: 'Twitch', key: 'live_SECRET123' } }))
fs.writeFileSync(path.join(cfg, 'basic/profiles/Main/obs-multi-rtmp.json'), JSON.stringify({ targets: [{ name: 'YouTube', 'service-param': { key: 'yt-SECRET456' } }] }))
const target = path.join(root, 'portable'); fs.mkdirSync(path.join(target, 'config/obs-studio/basic'), { recursive: true }); fs.mkdirSync(path.join(target, 'bin'), { recursive: true }); fs.writeFileSync(path.join(target, 'bin/obs'), '')
const withKeys = path.join(root, 'with-keys.obsbundle'), noKeys = path.join(root, 'no-keys.obsbundle')

;(async () => {
  const app = await electron.launch({
    executablePath: process.env.OBSCL_PACKAGED || APP + '/node_modules/electron/dist/electron',
    args: [...(process.env.OBSCL_PACKAGED ? [] : [APP]), '--no-sandbox', '--user-data-dir=' + path.join(root, 'ud')],
    env: { ...process.env, HOME: home, XDG_CONFIG_HOME: '' },
  })
  const page = await app.firstWindow()
  globalThis.__page = page
  page.on('pageerror', (e) => console.log('[pageerror]', e.message))
  await page.setViewportSize({ width: 1100, height: 1000 })
  await page.waitForSelector('text=What would you like to do?')
  await page.screenshot({ path: OUT + '/f0-home.png', fullPage: true })
  const saveTo = (p) => app.evaluate(({ dialog }, f) => { dialog.showSaveDialog = async (o) => { globalThis.__save = o; return { canceled: false, filePath: f } } }, p)
  const lastSave = () => app.evaluate(() => globalThis.__save)

  console.log('1. save WITHOUT keys (the default)')
  await page.click('text=Save my OBS setup to a file')
  await page.waitForSelector('text=Give this setup a name')
  check('stream keys are off by default', !(await page.locator('label:has-text("Include my stream keys") input').isChecked()))
  check('no warning shown while off', (await page.locator('text=Keep this file private').count()) === 0)
  await page.screenshot({ path: OUT + '/f1-save.png', fullPage: true })
  await saveTo(noKeys)
  await page.click('button:has-text("Save to a file…")')
  await page.waitForSelector('text=Saved.')
  check('file name has no warning mark', !(await lastSave()).defaultPath.includes('CONTAINS'))
  const body1 = await page.innerText('main')
  check('says what you will type again, in plain words', body1.includes('Stream key for Twitch') && body1.includes('Multiple RTMP outputs: “YouTube”'))
  check('does not show internal names like STREAM_KEY', !/STREAM_KEY|_SERVICE_PARAM/.test(body1))
  await page.screenshot({ path: OUT + '/f2-saved-plain.png', fullPage: true })
  const z1 = await JSZip.loadAsync(fs.readFileSync(noKeys))
  const texts1 = await Promise.all(Object.values(z1.files).filter((f) => !f.dir).map((f) => f.async('string')))
  check('no key anywhere inside the file', !texts1.join('\n').match(/live_SECRET123|yt-SECRET456/))

  console.log('2. save WITH keys: warned, labelled, still safe for git')
  await page.click('button:has-text("Save another")')
  await page.waitForSelector('text=Give this setup a name')
  await page.check('label:has-text("Include my stream keys") input')
  await page.waitForSelector('text=Keep this file private')
  await page.screenshot({ path: OUT + '/f3-save-keys.png', fullPage: true })
  await saveTo(withKeys)
  await page.click('button:has-text("Save to a file…")')
  await page.waitForSelector('text=This file contains your stream keys')
  check('suggested file name carries the warning', (await lastSave()).defaultPath.includes('(CONTAINS STREAM KEYS)'))
  const z2 = await JSZip.loadAsync(fs.readFileSync(withKeys))
  check('a README about the keys sits at the top of the zip', Object.keys(z2.files).includes('READ-ME-FIRST-CONTAINS-STREAM-KEYS.txt'))
  const man = JSON.parse(await z2.files['manifest.json'].async('string'))
  check('the file says so itself', man.containsSecrets === true && /stream as you/.test(man.warning))
  await page.screenshot({ path: OUT + '/f4-saved-keys.png', fullPage: true })

  console.log('3. load the file WITH keys: red warning, keys used without typing')
  await app.evaluate(({ dialog }, p) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [p] }) }, target)
  await page.click('nav >> text=OBS on this computer')
  await page.click('button:has-text("Add OBS from a folder")')
  await page.waitForSelector('text=added by you')
  await page.click('nav >> text=Load a setup')
  await app.evaluate(({ dialog }, p) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [p] }) }, withKeys)
  await page.click('button:has-text("Choose a file")')
  await page.waitForSelector('text=This file contains stream keys')
  await page.selectOption('select[aria-label="Which OBS"]', { label: 'OBS Studio (portable: portable) (OBS in a folder)' })
  await page.waitForSelector('text=Here is what will happen')
  await page.waitForSelector('text=Use the stream keys from the file')
  await page.evaluate(() => document.querySelector('main').scrollTo(0, 99999)); await page.waitForTimeout(300)
  await page.screenshot({ path: OUT + '/f5-load-keys.png' })
  await page.click('button:has-text("Load into OBS")')
  await page.waitForSelector('text=Done.')
  const svc = path.join(target, 'config/obs-studio/basic/profiles/Main/service.json')
  check('the key from the file is now in OBS', JSON.parse(fs.readFileSync(svc, 'utf8')).settings.key === 'live_SECRET123')

  console.log('4. load the file WITHOUT keys: the key OBS already has is kept')
  await page.click('button:has-text("Load another file")')
  await app.evaluate(({ dialog }, p) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [p] }) }, noKeys)
  await page.click('button:has-text("Choose a file")')
  await page.waitForSelector('text=Your stream keys')
  check('no red warning for a file without keys', (await page.locator('text=This file contains stream keys').count()) === 0)
  await page.selectOption('select[aria-label="Which OBS"]', { label: 'OBS Studio (portable: portable) (OBS in a folder)' })
  await page.waitForSelector('text=Keep the stream keys OBS already has')
  await page.evaluate(() => document.querySelector('main').scrollTo(0, 99999)); await page.waitForTimeout(300)
  await page.screenshot({ path: OUT + '/f6-load-plain.png' })
  await page.click('button:has-text("Load into OBS")')
  await page.waitForSelector('text=Done.')
  check('the existing key was not blanked', JSON.parse(fs.readFileSync(svc, 'utf8')).settings.key === 'live_SECRET123')
  await app.close()
  console.log(process.exitCode ? 'E2E-KEYS FAILED' : 'E2E-KEYS OK')
})().catch(async (e) => { console.error('E2E-KEYS FAIL', e.message); try { await globalThis.__page.screenshot({ path: OUT + '/f-fail.png', fullPage: true }) } catch {} process.exit(1) })

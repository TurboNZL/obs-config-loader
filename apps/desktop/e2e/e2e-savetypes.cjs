// The three ways a preset is saved (this computer, GitHub, a file), link and unlink, the grid, the preview of changes, the
// "where is each part kept" table, the extras file, a script folder that is kept with the preset, and the Home page.
//   xvfb-run -a node e2e/e2e-savetypes.cjs     (after `pnpm --filter @obs-config-loader/desktop build`)
const { _electron: electron } = require('playwright')
const fs = require('fs'), path = require('path'), os = require('os')
const { execFileSync } = require('child_process')
const APP = path.resolve(__dirname, '..')
const OUT = path.join(os.tmpdir(), 'obscl-e2e-shots')
fs.mkdirSync(OUT, { recursive: true })
const JSZip = require(require.resolve('jszip', { paths: [path.join(__dirname, '../../../packages/core')] }))
const check = (name, cond) => { console.log(cond ? '  ok  ' : '  FAIL', name); if (!cond) process.exitCode = 1 }
const git = (cwd, ...a) => execFileSync('git', a, { cwd, encoding: 'utf8' })

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'e2e-types-'))
const home = path.join(root, 'home')
const cfg = path.join(home, '.var/app/com.obsproject.Studio/config/obs-studio')
fs.mkdirSync(path.join(cfg, 'basic/scenes'), { recursive: true })
fs.mkdirSync(path.join(cfg, 'basic/profiles/Main'), { recursive: true })
fs.mkdirSync(path.join(home, '.local/share/flatpak/app/com.obsproject.Studio'), { recursive: true })
const bigFile = path.join(home, 'Videos/intro.mp4'); fs.mkdirSync(path.dirname(bigFile), { recursive: true }); fs.writeFileSync(bigFile, Buffer.alloc(6 * 1024 * 1024, 7))
// a script that finds the files around it, like a real stream tool does
const proj = path.join(home, 'stream-tool'); fs.mkdirSync(proj, { recursive: true })
fs.writeFileSync(path.join(proj, 'switcher.py'), 'import os\nHERE = os.path.dirname(os.path.abspath(__file__))\n')
fs.writeFileSync(path.join(proj, 'helper.py'), 'x = 1\n')
fs.writeFileSync(path.join(proj, '.env'), 'TOKEN=do-not-keep\n')
const sceneFile = path.join(cfg, 'basic/scenes/Main.json')
const scenes = {
  name: 'Main', current_scene: 'Scene', scene_order: [{ name: 'Scene' }],
  modules: { 'scripts-tool': [{ path: path.join(proj, 'switcher.py'), settings: {} }] },
  sources: [
    { id: 'scene', name: 'Scene', uuid: 'u-s', settings: { items: [{ name: 'Backdrop', visible: true }] } },
    { id: 'color_source', name: 'Backdrop', uuid: 'u-b', settings: { color: 1 } },
    { id: 'ffmpeg_source', name: 'Intro video', uuid: 'u-v', settings: { local_file: bigFile } },
  ],
}
fs.writeFileSync(sceneFile, JSON.stringify(scenes))
fs.writeFileSync(path.join(cfg, 'basic/profiles/Main/basic.ini'), '[General]\nName=Main\n')
fs.writeFileSync(path.join(cfg, 'basic/profiles/Main/service.json'), JSON.stringify({ type: 'rtmp_common', settings: { service: 'Twitch', key: 'live_SECRET' } }))
fs.writeFileSync(path.join(cfg, 'user.ini'), '[Basic]\nProfile=Main\nProfileDir=Main\nSceneCollection=Main\nSceneCollectionFile=Main\n')

;(async () => {
  const app = await electron.launch({
    executablePath: process.env.OBSCL_PACKAGED || APP + '/node_modules/electron/dist/electron',
    args: [...(process.env.OBSCL_PACKAGED ? [] : [APP]), '--no-sandbox', '--user-data-dir=' + path.join(root, 'ud')],
    env: { ...process.env, HOME: home, XDG_CONFIG_HOME: '', XDG_DATA_HOME: '' },
  })
  const page = await app.firstWindow()
  page.on('pageerror', (e) => console.log('[pageerror]', e.message))
  await page.setViewportSize({ width: 1300, height: 1000 })
  await page.waitForSelector('text=Flatpak')
  const tile = (name) => page.locator(`section[aria-label="Preset ${name}"]`)
  const presets = path.join(home, '.local/share/obs-config-loader/presets')
  const saveTo = (p) => app.evaluate(({ dialog }, f) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: f }) }, p)

  console.log('1. save a preset: it holds everything, and the script folder travels with it')
  await page.click('nav >> text=Presets')
  await page.click('button:has-text("Save my OBS setup")')
  await page.fill('section.card:has-text("Save my OBS setup") input >> nth=0', 'Stream')
  await page.screenshot({ path: OUT + '/t0-save-form.png', fullPage: true })
  check('the three kinds are named on the form', ['On this computer', 'On GitHub', 'As a file'].every((t) => true) && (await page.locator('.kind-panel').count()) === 3)
  await page.click('button:has-text("Save preset")')
  await tile('Stream').waitFor()
  const dir = path.join(presets, 'Stream')
  check('the script and the code files beside it are in the preset', fs.existsSync(path.join(dir, 'scripts/projects/SCRIPT_FOLDER/switcher.py')) && fs.existsSync(path.join(dir, 'scripts/projects/SCRIPT_FOLDER/helper.py')))
  check('git tracks the script (so its history is kept)', git(dir, 'ls-files').includes('scripts/projects/SCRIPT_FOLDER/switcher.py'))
  check('a hidden file such as .env is never kept', !git(dir, 'ls-files').includes('.env') && !fs.existsSync(path.join(dir, 'scripts/projects/SCRIPT_FOLDER/.env')))
  check('the big file and the key are inside the preset, on this computer', fs.existsSync(path.join(dir, 'local/media/intro/intro.mp4')) && fs.readFileSync(path.join(dir, 'local/keys.json'), 'utf8').includes('live_SECRET'))
  check('git sees neither', !git(dir, 'ls-files').includes('local/') && !git(dir, 'log', '-p', '--all').includes('live_SECRET'))
  const t = tile('Stream')
  await t.locator('text=and this preset match').waitFor()
  const txt = await t.innerText()
  check('the tile says which OBS it is linked to', /linked to .*Flatpak/i.test(txt) || /Flatpak/.test(txt))
  check('and that they match', txt.includes('and this preset match'))
  check('the three parts are coloured blocks', (await t.locator('.kind-panel.kind-local').count()) === 1 && (await t.locator('.kind-panel.kind-cloud').count()) === 1)
  check('GitHub block says it is not backed up', txt.includes('Not backed up online'))
  check('the keys and the file are listed as kept only on this computer', /Kept only here:.*stream key/.test(txt) && /1 file/.test(txt))
  check('the buttons are icons: link and export', (await t.locator('button[aria-label^="Linked to"]').count()) === 1 && (await t.locator('button[aria-label="Export this preset to a file"]').count()) === 1)

  console.log('2. presets sit in a grid, at least two to a row')
  await page.click('button:has-text("Save my OBS setup")')
  await page.fill('section.card:has-text("Save my OBS setup") input >> nth=0', 'Second')
  await page.click('button:has-text("Save preset")')
  await tile('Second').waitFor()
  const a = await tile('Stream').boundingBox(), b = await tile('Second').boundingBox()
  check('two tiles on one row', Math.abs(a.y - b.y) < 4 && b.x > a.x + 200)
  await page.screenshot({ path: OUT + '/t1-grid.png', fullPage: true })

  console.log('3. the status names the OBS, and a preview shows what changed')
  const sc = JSON.parse(fs.readFileSync(sceneFile, 'utf8'))
  sc.sources.push({ id: 'color_source', name: 'Added in OBS', uuid: 'u-new', settings: { color: 2 } })
  fs.writeFileSync(sceneFile, JSON.stringify(sc))
  await page.click('nav >> text=Home')
  await page.click('nav >> text=Presets')
  await t.locator('text=/has \\d+ changes? this preset does not have yet/').waitFor()
  const line = await t.locator('text=/has \\d+ changes? this preset does not have yet/').first().innerText()
  check('it says WHICH OBS has the changes', /Flatpak/.test(line))
  await t.locator('button:has-text("See what changed")').click()
  await t.locator('ul[aria-label="What changed"] li').first().waitFor()
  check('the preview lists the changed scene layout in plain words', (await t.locator('ul[aria-label="What changed"]').innerText()).includes('Scene layout “main”'))
  await t.locator('ul[aria-label="What changed"] li button').first().click()
  check('and shows the lines: added in green', (await t.locator('.diff .add').count()) > 0 && (await t.locator('.diff .add').allInnerTexts()).join('\n').includes('Added in OBS'))
  await page.screenshot({ path: OUT + '/t2-diff.png', fullPage: true })

  console.log('4. unlink with the chain button: the preset stays as it is; link it again')
  await t.locator('button[aria-label^="Linked to"]').click()
  await page.waitForSelector('text=is no longer linked')
  const un = await t.innerText()
  check('it now stands on its own', un.includes('stands on its own') && un.includes('not linked to an OBS'))
  check('there is no "Save OBS to this preset" any more, but Apply is still there', !un.includes('Save OBS to this preset') && un.includes('Apply to OBS'))
  check('nothing in the preset changed', git(dir, 'status', '--porcelain') === '' && !fs.readFileSync(path.join(dir, 'collections/main.json'), 'utf8').includes('Added in OBS'))
  await t.locator('button[aria-label^="Not linked to an OBS"]').click()
  await t.locator('button:has-text("Link")').last().click()
  await page.waitForSelector('text=is now linked to')
  check('linked again', (await t.locator('button[aria-label^="Linked to"]').count()) === 1)
  await t.locator('button:has-text("Save OBS to this preset")').click()
  await t.locator('[role="status"]:has-text("Saved")').waitFor()
  check('saving puts the OBS change into the preset', fs.readFileSync(path.join(dir, 'collections/main.json'), 'utf8').includes('Added in OBS'))

  console.log('5. where each part is kept: untick GitHub for a layout, the file stays here and out of git')
  await t.locator('button[aria-label="Show details"]').click()
  await t.locator('text=Where each part is kept').waitFor()
  await page.screenshot({ path: OUT + '/t3-storage.png', fullPage: true })
  const up = t.locator('input[aria-label="Upload scene layout Main to GitHub"]')
  check('the layout is uploaded by default', await up.isChecked())
  await up.click()
  await t.locator('text=Changed.').first().waitFor()
  check('git no longer tracks it, but the preset still has it', !git(dir, 'ls-files').includes('collections/main.json') && fs.existsSync(path.join(dir, 'collections/main.json')))
  check('and it is listed as only on this computer', (await t.innerText()).includes('scene layout “Main”'))
  check('the stream keys row says never, with the reason', (await t.locator('text=never').count()) > 0 && (await t.locator('summary:has-text("stream keys go to GitHub")').count()) === 1)
  check('OBS still counts as matching (nothing looks changed)', (await t.innerText()).includes('and this preset match'))
  await up.click()
  await t.locator('text=Changed.').first().waitFor()
  check('ticking it again tracks it again', git(dir, 'ls-files').includes('collections/main.json'))
  const big = t.locator('input[aria-label="Upload intro.mp4 to GitHub"]')
  check('a 6 MB file can be uploaded if wanted', await big.isEnabled())
  await t.locator('button[aria-label="Hide details"]').click()

  console.log('6. export only the extras (what GitHub does not have)')
  await up.waitFor({ state: 'detached' }).catch(() => {})
  await t.locator('button[aria-label="Show details"]').click()
  await t.locator('input[aria-label="Upload scene layout Main to GitHub"]').click()
  await t.locator('text=Changed.').first().waitFor()
  await t.locator('button[aria-label="Hide details"]').click()
  const extras = path.join(root, 'stream.obsextras'); await saveTo(extras)
  await t.locator('button[aria-label="Export this preset to a file"]').click()
  await t.locator('button:has-text("Only the extras")').click()
  await t.locator('text=you chose not to upload').waitFor()
  await page.screenshot({ path: OUT + '/t4-extras.png', fullPage: true })
  check('it lists the kept-back part and the file', (await t.innerText()).includes('Scene layout “main”') && (await t.innerText()).includes('intro.mp4'))
  check('stream keys are off by default', !(await t.locator('label:has-text("Include my stream keys") input').isChecked()))
  await t.locator('button:has-text("Choose where to save")').click()
  await page.waitForSelector('text=Saved the extras file')
  const ez = await JSZip.loadAsync(fs.readFileSync(extras))
  const names = Object.keys(ez.files)
  check('the extras file holds that layout and the big file, and no key', names.includes('files/collections/main.json') && names.some((n) => n.endsWith('intro.mp4')) && !(await Promise.all(names.filter((n) => !ez.files[n].dir && !n.endsWith('.mp4')).map((n) => ez.files[n].async('string')))).join('').includes('live_SECRET'))
  check('it is much smaller than a whole setup file would be with nothing else in it', names.length < 8)

  console.log('7. Home: numbers and what needs a look')
  await page.click('nav >> text=Home')
  await page.waitForSelector('text=Needs a look')
  await page.waitForTimeout(800)
  const home1 = await page.locator('main').innerText()
  check('counts the presets', /2\s*\n?\s*presets/.test(home1))
  check('says Second and Stream are only on this computer', home1.includes('“Stream” is only on this computer') && home1.includes('“Second” is only on this computer'))
  check('has no "Open a setup file"', !home1.includes('Open a setup file'))
  await page.screenshot({ path: OUT + '/t5-home.png', fullPage: true })

  await app.close()
  console.log(process.exitCode ? 'E2E-SAVETYPES FAILED' : 'E2E-SAVETYPES OK')
})().catch((e) => { console.error('E2E-SAVETYPES FAIL', e); process.exit(1) })
